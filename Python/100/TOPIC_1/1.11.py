# 1.11 Create two numbers: a = 10, b = 3.
#      Print their sum, difference, product, division, integer division, and remainder.
#      Each on its own line.
a = 10
b = 3
print(f'Sum: {a+b}')
print(f'Difference: {a-b}')
print(f'Product: {a*b}')
print(f'Division: {a/b}')
print(f'Integer division: {f"{a//b}"}')
print(f'Remainder: {a%b}')
