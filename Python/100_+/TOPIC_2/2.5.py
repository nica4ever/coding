# 25. Given a list of (timestamp, ip) tuples, count requests per minute.
#     Return dict {minute: count}.

events = [
    ("2024-03-15 10:00:15", "10.0.0.1"),
    ("2024-03-15 10:00:22", "10.0.0.2"),
    ("2024-03-15 10:00:45", "10.0.0.1"),
    ("2024-03-15 10:01:03", "10.0.0.3"),
    ("2024-03-15 10:01:18", "10.0.0.1"),
    ("2024-03-15 10:01:55", "10.0.0.2"),
    ("2024-03-15 10:02:05", "10.0.0.1"),
    ("2024-03-15 10:02:33", "10.0.0.4"),
    ("2024-03-15 10:03:12", "10.0.0.2"),
    ("2024-03-15 10:03:48", "10.0.0.3"),
    ("2024-03-15 10:04:02", "10.0.0.1"),
    ("2024-03-15 10:04:30", "10.0.0.1"),
    ("2024-03-15 10:05:05", "10.0.0.2"),
    ("2024-03-15 10:05:44", "10.0.0.5"),
]

def requests_minute(logs):
    min_ip = {}
    for time, ip in logs:
        minutes = ":".join(time.split()[1].split(":")[:2])
        min_ip[minutes] = min_ip.get(minutes, 0) + 1
    return min_ip
print(requests_minute(events))
